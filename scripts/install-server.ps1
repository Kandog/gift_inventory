<#
.SYNOPSIS
  Installs the Gift Inventory server so it starts with Windows and keeps running without anyone signed in.

.DESCRIPTION
  Run once, in PowerShell opened with "Run as administrator", from the project folder:
      powershell -ExecutionPolicy Bypass -File scripts\install-server.ps1

  It will:
    1. Install packages and build the dashboard.
    2. Register a startup task "GiftInventory" (Task Scheduler) that runs the server as the Windows
       account you enter, restarts it if it stops, and has no time limit.
    3. Allow the server port through Windows Firewall on Private/Domain networks, so phones can connect.
    4. Optionally (-DisableSleep) stop the PC sleeping while plugged in.

  The account you enter must be able to write to the backup network share.
  Re-running the script updates the existing task.
#>
param(
  [int]$Port = 8080,
  [string]$DataDir = (Join-Path (Split-Path $PSScriptRoot -Parent) 'data'),
  [string]$TaskName = 'GiftInventory',
  [switch]$DisableSleep
)

$ErrorActionPreference = 'Stop'
$Repo = Split-Path $PSScriptRoot -Parent

$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $isAdmin) { throw 'Please run this in PowerShell opened with "Run as administrator".' }

$node = (Get-Command node -ErrorAction SilentlyContinue).Source
if (-not $node) { throw 'Node.js is not installed. Install Node.js 24 LTS from nodejs.org, then run this again.' }
$major = [int]((& $node -p 'process.versions.node.split(".")[0]'))
if ($major -lt 24) { throw "Node.js 24 or newer is required (found $major)." }

Write-Host '1/4 Installing packages and building the dashboard...' -ForegroundColor Cyan
Push-Location $Repo
try {
  npm install --no-audit --no-fund
  if ($LASTEXITCODE -ne 0) { throw 'npm install failed' }
  npm run build -w @gifts/dashboard
  if ($LASTEXITCODE -ne 0) { throw 'Dashboard build failed' }
} finally { Pop-Location }

New-Item -ItemType Directory -Force -Path (Join-Path $DataDir 'logs') | Out-Null

# The task runs this small launcher so output is captured in data\logs\server.log.
$launcher = Join-Path $Repo 'scripts\run-server.cmd'
$tsx = Join-Path $Repo 'node_modules\tsx\dist\cli.mjs'
$main = Join-Path $Repo 'apps\server\src\main.ts'
@"
@echo off
rem Generated by install-server.ps1. Started by the "$TaskName" task at boot.
set GIFTS_PORT=$Port
set GIFTS_DATA_DIR=$DataDir
cd /d "$Repo"
"$node" "$tsx" "$main" >> "$DataDir\logs\server.log" 2>&1
"@ | Set-Content -Path $launcher -Encoding ASCII

Write-Host '2/4 Registering the startup task...' -ForegroundColor Cyan
$cred = Get-Credential -Message 'Windows account the server runs as (it needs write access to the backup share)' -UserName "$env:USERDOMAIN\$env:USERNAME"
$action = New-ScheduledTaskAction -Execute 'cmd.exe' -Argument "/c `"$launcher`"" -WorkingDirectory $Repo
$trigger = New-ScheduledTaskTrigger -AtStartup
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
  -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) -ExecutionTimeLimit ([TimeSpan]::Zero) -MultipleInstances IgnoreNew
if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
  Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
  Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
}
Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings `
  -User $cred.UserName -Password $cred.GetNetworkCredential().Password -RunLevel Limited `
  -Description 'Gift Inventory server (API + dashboard). See scripts\install-server.ps1.' | Out-Null

Write-Host '3/4 Allowing the port through Windows Firewall...' -ForegroundColor Cyan
$ruleName = "Gift Inventory (TCP $Port)"
Get-NetFirewallRule -DisplayName $ruleName -ErrorAction SilentlyContinue | Remove-NetFirewallRule
New-NetFirewallRule -DisplayName $ruleName -Direction Inbound -Protocol TCP -LocalPort $Port -Action Allow -Profile Private, Domain | Out-Null
$public = Get-NetConnectionProfile | Where-Object NetworkCategory -eq 'Public'
if ($public) {
  Write-Warning ("Windows treats '{0}' as a Public network, so phones will be blocked. If this is your office network, run:`n    Set-NetConnectionProfile -InterfaceAlias '{1}' -NetworkCategory Private" -f $public[0].Name, $public[0].InterfaceAlias)
}

Write-Host '4/4 Power settings...' -ForegroundColor Cyan
if ($DisableSleep) {
  powercfg /change standby-timeout-ac 0
  powercfg /change hibernate-timeout-ac 0
  Write-Host '   Sleep and hibernate disabled while plugged in.'
} else {
  Write-Host '   Skipped. Make sure this PC never sleeps (or re-run with -DisableSleep), or phones cannot sync.'
}

Start-ScheduledTask -TaskName $TaskName
Start-Sleep -Seconds 5
try {
  $health = Invoke-RestMethod -Uri "http://localhost:$Port/api/health" -TimeoutSec 10
  if ($health.ok) { Write-Host "`nGift Inventory is running." -ForegroundColor Green }
} catch {
  Write-Warning "The server did not answer yet. Check $DataDir\logs\server.log"
}
$ips = Get-NetIPAddress -AddressFamily IPv4 | Where-Object { $_.IPAddress -notlike '127.*' -and $_.IPAddress -notlike '169.254.*' } | Select-Object -ExpandProperty IPAddress
foreach ($ip in $ips) { Write-Host "   Dashboard: http://${ip}:$Port" }
Write-Host '   Tip: give this PC a fixed IP in your router (DHCP reservation) so phones always find it.'
